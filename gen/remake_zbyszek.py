"""Create Zbyszek as a compact, hard-edged pixel NPC matching the game atlas."""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
S = 8
W, H = 120, 180
im = Image.new("RGBA", (W * S, H * S), (0, 0, 0, 0))
d = ImageDraw.Draw(im)

def r(box, color):
    d.rectangle(tuple(v * S for v in box), fill=color)

def poly(points, color):
    d.polygon([(x * S, y * S) for x, y in points], fill=color)

outline = "#211d24"
# boots and legs silhouette
r((32, 151, 54, 173), outline); r((63, 151, 87, 173), outline)
r((35, 150, 52, 169), "#70452e"); r((65, 150, 84, 169), "#70452e")
r((35, 157, 52, 165), "#9a6240"); r((65, 157, 84, 165), "#9a6240")
r((31, 169, 57, 175), outline); r((62, 169, 90, 175), outline)
r((34, 168, 55, 171), "#33252a"); r((65, 168, 87, 171), "#33252a")
# jeans
poly([(35, 103), (55, 100), (62, 108), (61, 153), (33, 153)], outline)
poly([(63, 106), (85, 102), (88, 153), (62, 153)], outline)
r((39, 108, 58, 149), "#243e60"); r((66, 108, 82, 149), "#243e60")
r((40, 119, 57, 127), "#355b7d"); r((67, 133, 82, 141), "#355b7d")
r((55, 109, 62, 151), "#172a47"); r((62, 110, 68, 151), "#172a47")
# jacket outline and arms
poly([(28, 66), (42, 57), (78, 57), (95, 72), (91, 121), (78, 132), (67, 118), (53, 118), (41, 133), (26, 120)], outline)
r((24, 78, 42, 119), outline); r((79, 75, 98, 119), outline)
r((27, 82, 40, 116), "#923c38"); r((82, 79, 95, 116), "#923c38")
r((29, 90, 40, 97), "#c4614e"); r((83, 101, 95, 108), "#c4614e")
# open red plaid jacket panels
poly([(30, 68), (47, 59), (57, 71), (53, 113), (42, 126), (29, 116)], "#a9463f")
poly([(72, 61), (86, 69), (91, 115), (78, 126), (67, 113), (65, 72)], "#a9463f")
for box, col in [((31, 76, 45, 84), "#d17b58"), ((30, 96, 43, 104), "#6f3035"), ((43, 67, 54, 74), "#df9b69"), ((42, 108, 53, 116), "#6f3035"), ((75, 72, 87, 80), "#df9b69"), ((77, 91, 90, 99), "#6f3035"), ((69, 105, 81, 114), "#d17b58")]:
    r(box, col)
# black undershirt and collar
poly([(48, 65), (61, 56), (73, 65), (69, 112), (59, 119), (50, 111)], "#24242d")
r((45, 62, 57, 70), "#d59a70"); r((64, 62, 76, 70), "#d59a70")
r((55, 73, 67, 104), "#30313c")
# hands
r((24, 115, 36, 128), outline); r((84, 114, 97, 128), outline)
r((27, 116, 35, 126), "#bd795b"); r((86, 115, 94, 126), "#bd795b")
# neck and head
r((46, 43, 76, 68), outline); r((50, 45, 72, 67), "#b97557")
r((42, 21, 83, 56), outline); r((46, 24, 79, 55), "#c5815f")
r((47, 40, 78, 53), "#a96652"); r((49, 31, 75, 45), "#d4936c")
# ears, nose, eyes, beard
r((41, 32, 47, 45), "#ad6b55"); r((77, 33, 83, 44), "#ad6b55")
r((52, 33, 57, 37), "#30252b"); r((67, 33, 72, 37), "#30252b")
r((56, 37, 61, 42), "#e0a07a"); r((58, 41, 68, 47), "#6c4b43")
r((53, 44, 73, 53), "#6b4a43"); r((58, 50, 69, 57), "#503c3a")
r((51, 49, 56, 53), "#8b5a4d"); r((70, 48, 75, 52), "#8b5a4d")
# cap and badge
poly([(40, 28), (45, 13), (55, 7), (74, 8), (83, 17), (81, 29), (70, 25), (51, 26)], outline)
poly([(45, 25), (48, 14), (57, 10), (73, 11), (79, 19), (77, 26), (59, 23)], "#465541")
r((52, 12, 73, 18), "#5e6b4f"); r((48, 22, 62, 28), "#334637")
poly([(42, 25), (58, 24), (68, 27), (45, 31)], "#334637")
r((59, 13, 68, 19), "#e8d5ae"); r((62, 15, 68, 17), "#b8423f")
# block highlights
r((33, 132, 38, 146), "#47698c"); r((78, 119, 84, 132), "#47698c")

out = im.resize((960, 1440), Image.Resampling.NEAREST)
out.save(ROOT / "gen/npc_src/zbyszek.png")
print(f"wrote {out.size[0]}x{out.size[1]} Zbyszek sprite")
