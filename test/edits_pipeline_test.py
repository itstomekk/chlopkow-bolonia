"""E2 generation-pipeline harness - runs the real generators SAFELY.

    python test/edits_pipeline_test.py             # equals gate: empty edits must reproduce the
                                                   # reproducible baseline byte-for-byte (SHA-256)
    python test/edits_pipeline_test.py --fixture   # smoke run with test/fixtures/edits_sample.json;
                                                   # C02 asserts forest.add/remove and water.add change
                                                   # ground/terrain/collision in the expected windows,
                                                   # C03 trees/collision, C04 entities/zones

Safety model
------------
The generators write to fixed paths in docs/ (docs/map.json, docs/items.json,
docs/img/map_*.png) and do not yet support an output-directory override, so the
harness uses full backup/restore:

  1. SHA-256 every protected output and copy it into a temp backup dir
     (TMPDIR -> Hermes scratch on this machine, pruned after 24 h);
  2. run `python osm/render_map.py` then `python osm/place_items.py` in the
     worktree root with ARK_EDITS pointing at a fixture;
  3. equals gate: assert post-run bytes == EXPECTED_BASELINE below (the empty-
     edits output measured during C01, deterministically reproducible);
  4. restore the originals from the backup in a `finally` and PROVE the
     restoration with hashes before exiting - even when a step above failed.

Both modes must exit with the real docs/ files byte-identical to how they were
found. Phase C is serialized on the map (exclusive lock), so no concurrent
writer can touch docs/ while this test runs. The equals gate sets ARK_EDITS to
the EMPTY fixture on purpose: the gate stays hermetic no matter what
osm/edits.json contains in the worktree ("empty or missing edits must leave
every output unchanged").

Baseline reproducibility note (measured 2026-09-29, C01)
--------------------------------------------------------
EXPECTED_BASELINE was captured by running the pipeline twice with EMPTY edits
(full render + isolated place_items rerun against restored committed inputs);
both runs were byte-identical. docs/map.json matches the committed bytes, but
the committed items.json and the four PNGs do NOT (PNG difference is encoding
only: identical decoded pixels, P vs L mode / palette emitted by this PIL;
items.json difference is real content - see below). A WARNING is printed when
the pre-run docs/ state differs from EXPECTED_BASELINE; the gate still passes
as long as the re-render is deterministic and the originals are restored.

The committed items.json was NOT produced by the current osm/ code in this
environment: running place_items.py on the exact committed map.json + PNGs
yields the regenerated bytes (e6d79b49...), not the committed ones
(355d71f1...). osm/ is unchanged since the last docs commit (61bfd91), so the
drift comes from the environment (most likely numpy 2.x's changed default sort
kind; it re-orders equally-good candidate spots in near_free/board placement).
C02 must regenerate and commit docs/ (or pin the gate to decoded equality)
as part of landing its hooks.

Exit code: 0 all good, 1 any failure.
"""
