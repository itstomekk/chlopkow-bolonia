def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def rel_key(rel):
    return rel.replace('/', '__')


def run_pipeline(edits_path):
    """Run render_map.py then place_items.py with ARK_EDITS set. Returns [(cmd, rc, tail), ...] for failures only."""
    env = dict(os.environ, ARK_EDITS=edits_path, PYTHONIOENCODING='utf-8')
    bad = []
    for script in ('osm/render_map.py', 'osm/place_items.py'):
        print(f'-- running: {sys.executable} {script}')
        p = subprocess.run([sys.executable, script], cwd=ROOT, env=env,
                           capture_output=True, text=True, timeout=TIMEOUT)
        tail = ((p.stdout or '') + (p.stderr or ''))[-800:].replace('\n', ' | ')
        if tail.strip():
            print('   tail:', tail[-600:])
        if p.returncode:
            bad.append((script, p.returncode, tail))
    return bad


