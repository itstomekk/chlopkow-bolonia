/*
 * Optional Nostr global chat for Arek w Chłopkowie.
 *
 * Integration (after the game scripts):
 *   <script src="js/chat.js"></script>
 *
 * This is deliberately a new-file-only feature. It does not talk to the game
 * canvas and it does not require a server. The first click on GLOBAL CHAT is
 * the opt-in point; before that click it makes no network request.
 *
 * CHANNEL_ID is the id of a real NIP-28 kind-40 channel-creation event, not a
 * locally invented identifier. It was published and read back from the relays
 * listed below. Creating a replacement channel would require a live relay
 * connection and would require updating every client at the same time.
 *
 * nostr-tools is loaded only after opt-in from a pinned ESM CDN URL. The guest
 * private key is generated by nostr-tools and kept only in this browser's
 * localStorage. No key or secret is shipped in this repository.
 */
'use strict';
(() => {
  const CHANNEL_ID = '6432fea61ded982c2ac4cc63afd224c61a9858f6e85d09578f87bca1f9f4fbcc';
  const RELAYS = Object.freeze([
    'wss://relay.damus.io',
    'wss://nos.lol',
    'wss://relay.primal.net',
    'wss://relay.nostr.band',
  ]);
  const NOSTR_TOOLS_URL = 'https://esm.sh/nostr-tools@2.25.2?bundle&target=es2020';
  const SECRET_KEY_STORAGE = 'arek-chlopkowie-nostr-guest-secret-v1';
  const NICKNAME_STORAGE = 'arek-chlopkowie-nostr-nickname-v1';
  const MAX_MESSAGE_CHARS = 100;
  const MAX_NICKNAME_CHARS = 24;

  const state = {
    open: false,
    started: false,
    connected: false,
    tools: null,
    secretKey: null,
    pubkey: '',
    pool: null,
    subscription: null,
    events: new Map(),
    eoseTimer: null,
  };

  const unicodeLength = value => Array.from(String(value)).length;
  const trimUnicode = (value, max) => Array.from(String(value)).slice(0, max).join('');

  function el(tag, text, parent) {
    const node = document.createElement(tag);
    if (text !== undefined) node.textContent = text;
    if (parent) parent.appendChild(node);
    return node;
  }

  const style = document.createElement('style');
  style.textContent = `
    #arek-global-chat, #arek-global-chat * { box-sizing: border-box; }
    #arek-global-chat {
      position: fixed; z-index: 10000; right: 12px; bottom: 12px;
      width: min(360px, calc(100vw - 24px));
      color: #f4e6c1; font: 12px/1.35 "Silkscreen", monospace;
      text-shadow: 1px 1px #111; pointer-events: none;
    }
    #arek-global-chat button, #arek-global-chat input, #arek-global-chat textarea {
      color: #f4e6c1; background: #172238; border: 1px solid #6e7897;
      border-radius: 3px; font: inherit; text-shadow: inherit;
    }
    #arek-global-chat button { cursor: pointer; padding: 7px 9px; }
    #arek-global-chat button:hover, #arek-global-chat button:focus-visible {
      background: #26385b; border-color: #ffd21f; outline: none;
    }
    #arek-chat-launch {
      display: block; margin-left: auto; pointer-events: auto;
      background: #182942; border-color: #ffd21f; color: #ffd21f;
      box-shadow: 2px 2px 0 #090d18;
    }
    #arek-chat-panel {
      display: none; pointer-events: auto; overflow: hidden;
      border: 2px solid #ffd21f; border-radius: 4px;
      background: rgba(12, 15, 28, .96); box-shadow: 3px 3px 0 #090d18;
    }
    #arek-chat-header { display: flex; align-items: center; gap: 8px; padding: 8px 9px 5px; }
    #arek-chat-title { flex: 1; color: #ffd21f; }
    #arek-chat-close { padding: 3px 7px !important; }
    #arek-chat-status { min-height: 17px; padding: 0 9px 5px; color: #a8b4cc; }
    #arek-chat-status[data-error="true"] { color: #ff837c; }
    #arek-chat-messages {
      height: 190px; overflow-y: auto; padding: 7px 9px;
      background: rgba(5, 8, 17, .75); border-top: 1px solid #394667;
      border-bottom: 1px solid #394667;
    }
    .arek-chat-message { margin: 0 0 7px; overflow-wrap: anywhere; }
    .arek-chat-message:last-child { margin-bottom: 0; }
    .arek-chat-meta { color: #8fa0c3; font-size: 10px; }
    .arek-chat-name { color: #ffd21f; }
    .arek-chat-empty { color: #8490a9; }
    #arek-chat-form { padding: 8px 9px 9px; }
    #arek-chat-nickname, #arek-chat-text { width: 100%; padding: 7px; }
    #arek-chat-nickname { margin-bottom: 6px; }
    #arek-chat-text { display: block; min-height: 50px; resize: vertical; }
    #arek-chat-actions { display: flex; align-items: center; gap: 8px; margin-top: 6px; }
    #arek-chat-count { flex: 1; color: #8490a9; font-size: 10px; }
    #arek-chat-send { color: #111; background: #ffd21f; border-color: #fff0a2; text-shadow: none; }
    #arek-chat-send:disabled { cursor: wait; opacity: .6; }
    @media (max-width: 480px) {
      #arek-global-chat { right: 8px; bottom: 8px; width: calc(100vw - 16px); }
      #arek-chat-messages { height: 145px; }
    }
  `;
  document.head.appendChild(style);

  const root = el('aside');
  root.id = 'arek-global-chat';
  root.setAttribute('aria-label', 'Global chat');
  const launch = el('button', 'GLOBAL CHAT', root);
  launch.id = 'arek-chat-launch';
  launch.type = 'button';
  launch.title = 'Open the optional global chat';

  const panel = el('section', undefined, root);
  panel.id = 'arek-chat-panel';
  panel.setAttribute('aria-label', 'Global Nostr chat');
  const header = el('div', undefined, panel);
  header.id = 'arek-chat-header';
  el('div', 'GLOBAL CHAT', header).id = 'arek-chat-title';
  const close = el('button', '×', header);
  close.id = 'arek-chat-close';
  close.type = 'button';
  close.setAttribute('aria-label', 'Close global chat');
  const status = el('div', 'Clicking chat connects to public Nostr relays.', panel);
  status.id = 'arek-chat-status';
  const messages = el('div', undefined, panel);
  messages.id = 'arek-chat-messages';
  messages.setAttribute('aria-live', 'polite');
  const empty = el('div', 'No messages yet.', messages);
  empty.className = 'arek-chat-empty';
  const form = el('form', undefined, panel);
  form.id = 'arek-chat-form';
  const nickname = el('input', undefined, form);
  nickname.id = 'arek-chat-nickname';
  nickname.type = 'text';
  nickname.placeholder = 'Nickname';
  nickname.autocomplete = 'nickname';
  nickname.maxLength = MAX_NICKNAME_CHARS;
  nickname.setAttribute('aria-label', 'Nickname');
  const text = el('textarea', undefined, form);
  text.id = 'arek-chat-text';
  text.placeholder = 'Write a message...';
  text.rows = 2;
  text.setAttribute('aria-label', 'Message');
  const actions = el('div', undefined, form);
  actions.id = 'arek-chat-actions';
  const count = el('span', `0/${MAX_MESSAGE_CHARS}`, actions);
  count.id = 'arek-chat-count';
  const send = el('button', 'SEND', actions);
  send.id = 'arek-chat-send';
  send.type = 'submit';
  document.body.appendChild(root);
  // Chat typing must never trigger the game's WASD, jump or map shortcuts.
  root.addEventListener('keydown', event => event.stopPropagation());

  function setStatus(value, error) {
    status.textContent = value;
    status.dataset.error = error ? 'true' : 'false';
  }

  function storageGet(key) {
    try { return localStorage.getItem(key); } catch (e) { throw new Error('browser storage is unavailable'); }
  }

  function storageSet(key, value) {
    try { localStorage.setItem(key, value); } catch (e) { throw new Error('browser storage is unavailable'); }
  }

  function bytesToHex(bytes) {
    return Array.from(bytes, byte => byte.toString(16).padStart(2, '0')).join('');
  }

  function hexToBytes(hex) {
    if (!/^[0-9a-f]{64}$/i.test(hex)) return null;
    const bytes = new Uint8Array(32);
    for (let i = 0; i < bytes.length; i++) bytes[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
    return bytes;
  }

  function getGuestSecret(tools) {
    const stored = storageGet(SECRET_KEY_STORAGE);
    const existing = stored && hexToBytes(stored);
    if (existing) return existing;
    const generated = tools.generateSecretKey();
    if (!(generated instanceof Uint8Array) || generated.length !== 32) throw new Error('nostr-tools did not create a valid guest key');
    storageSet(SECRET_KEY_STORAGE, bytesToHex(generated));
    return generated;
  }

  function getNickname() {
    let value = nickname.value;
    if (!value) {
      try { value = storageGet(NICKNAME_STORAGE) || ''; } catch (e) { value = ''; }
    }
    value = trimUnicode(value.trim(), MAX_NICKNAME_CHARS);
    return value || (state.pubkey ? `guest-${state.pubkey.slice(0, 6)}` : 'guest');
  }

  function saveNickname() {
    nickname.value = trimUnicode(nickname.value, MAX_NICKNAME_CHARS);
    try { storageSet(NICKNAME_STORAGE, nickname.value); } catch (e) { setStatus(e.message, true); }
  }

  function renderMessages() {
    messages.replaceChildren();
    const list = Array.from(state.events.values()).sort((a, b) => a.created_at - b.created_at || a.id.localeCompare(b.id));
    if (!list.length) {
      const blank = el('div', 'No messages yet.', messages);
      blank.className = 'arek-chat-empty';
      return;
    }
    for (const event of list) {
      const row = el('div', undefined, messages);
      row.className = 'arek-chat-message';
      const meta = el('div', undefined, row);
      meta.className = 'arek-chat-meta';
      const name = el('span', event.nickname, meta);
      name.className = 'arek-chat-name';
      el('span', ` · ${new Date(event.created_at * 1000).toLocaleTimeString()}`, meta);
      el('div', event.content, row);
    }
    messages.scrollTop = messages.scrollHeight;
  }

  function addEvent(event) {
    if (!event || event.kind !== 42 || typeof event.id !== 'string' || typeof event.content !== 'string') return;
    const tags = Array.isArray(event.tags) ? event.tags : [];
    const rootTag = tags.find(tag => Array.isArray(tag) && tag[0] === 'e' && tag[1] === CHANNEL_ID && (tag[3] === 'root' || !tag[3]));
    if (!rootTag || unicodeLength(event.content) > MAX_MESSAGE_CHARS) return;
    if (state.events.has(event.id)) return;
    const nameTag = tags.find(tag => Array.isArray(tag) && tag[0] === 'name' && typeof tag[1] === 'string');
    const fallback = event.pubkey ? `guest-${event.pubkey.slice(0, 6)}` : 'guest';
    const name = trimUnicode((nameTag ? nameTag[1] : fallback).trim(), MAX_NICKNAME_CHARS) || fallback;
    state.events.set(event.id, {
      id: event.id,
      created_at: Number.isFinite(event.created_at) ? event.created_at : 0,
      content: event.content,
      nickname: name,
    });
    if (state.events.size > 200) {
      const oldest = Array.from(state.events.values()).sort((a, b) => a.created_at - b.created_at)[0];
      state.events.delete(oldest.id);
    }
    renderMessages();
  }

  async function start() {
    if (state.started) return;
    state.started = true;
    setStatus('Connecting to public Nostr relays...');
    try {
      if (!navigator.onLine) throw new Error('browser is offline');
      const tools = await import(NOSTR_TOOLS_URL);
      if (typeof tools.generateSecretKey !== 'function' || typeof tools.getPublicKey !== 'function' || typeof tools.finalizeEvent !== 'function' || typeof tools.SimplePool !== 'function') {
        throw new Error('nostr-tools API is incompatible');
      }
      state.tools = tools;
      state.secretKey = getGuestSecret(tools);
      state.pubkey = tools.getPublicKey(state.secretKey);
      state.pool = new tools.SimplePool();
      state.subscription = state.pool.subscribeMany(
        RELAYS,
        [{ kinds: [42], '#e': [CHANNEL_ID], limit: 100 }],
        {
          onevent: addEvent,
          oneose: () => {
            state.connected = true;
            if (state.eoseTimer) clearTimeout(state.eoseTimer);
            setStatus('Connected. Messages are public across clients.');
          },
          onclose: reason => {
            state.connected = false;
            state.started = false;
            state.subscription = null;
            const detail = reason ? ` (${String(reason)})` : '';
            setStatus(`Relay connection closed${detail}. Try again later.`, true);
          },
        },
      );
      state.eoseTimer = setTimeout(() => {
        if (!state.connected) setStatus('Relay connection timed out. Check your network and try again.', true);
      }, 15000);
      const savedNickname = storageGet(NICKNAME_STORAGE);
      if (savedNickname) nickname.value = trimUnicode(savedNickname, MAX_NICKNAME_CHARS);
      setStatus('Connected; waiting for channel messages...');
    } catch (error) {
      state.started = false;
      state.connected = false;
      if (state.pool && state.pool.close) state.pool.close(RELAYS);
      state.pool = null;
      setStatus(`Chat unavailable: ${error.message || 'relay or library error'}`, true);
    }
  }

  async function sendMessage() {
    if (!state.started || !state.pool || !state.tools || !state.secretKey) {
      setStatus('Chat is not connected. Open it again to retry.', true);
      return;
    }
    const content = trimUnicode(text.value, MAX_MESSAGE_CHARS);
    text.value = content;
    updateCount();
    if (!content.trim()) return;
    send.disabled = true;
    setStatus('Publishing to public relays...');
    const event = state.tools.finalizeEvent({
      kind: 42,
      created_at: Math.floor(Date.now() / 1000),
      tags: [
        ['e', CHANNEL_ID, RELAYS[0], 'root'],
        ['name', getNickname()],
        ['client', 'arek-w-chlopkowie'],
      ],
      content,
    }, state.secretKey);
    try {
      const results = await Promise.allSettled(state.pool.publish(RELAYS, event));
      const accepted = results.filter(result => result.status === 'fulfilled').length;
      if (!accepted) throw new Error('no relay accepted the message');
      addEvent(event);
      text.value = '';
      updateCount();
      const failed = results.length - accepted;
      setStatus(failed ? `Sent to ${accepted} relay(s); ${failed} unavailable.` : 'Message sent to Nostr.');
    } catch (error) {
      setStatus(`Message not sent: ${error.message || 'all relays failed'}`, true);
    } finally {
      send.disabled = false;
    }
  }

  function updateCount() {
    if (unicodeLength(text.value) > MAX_MESSAGE_CHARS) text.value = trimUnicode(text.value, MAX_MESSAGE_CHARS);
    count.textContent = `${unicodeLength(text.value)}/${MAX_MESSAGE_CHARS}`;
  }

  function openChat() {
    state.open = true;
    launch.style.display = 'none';
    panel.style.display = 'block';
    nickname.focus();
    start();
  }

  function closeChat() {
    state.open = false;
    panel.style.display = 'none';
    launch.style.display = 'block';
  }

  launch.addEventListener('click', openChat);
  close.addEventListener('click', closeChat);
  nickname.addEventListener('input', saveNickname);
  text.addEventListener('input', updateCount);
  text.addEventListener('keydown', event => {
    if (event.key === 'Enter' && !event.shiftKey) {
      event.preventDefault();
      form.requestSubmit();
    }
  });
  form.addEventListener('submit', event => {
    event.preventDefault();
    sendMessage();
  });

  // A tiny public hook makes static/browser smoke-tests possible without
  // exposing the private key or changing the game's own globals.
  window.__arekGlobalChat = Object.freeze({
    channelId: CHANNEL_ID,
    relays: RELAYS.slice(),
    maxMessageChars: MAX_MESSAGE_CHARS,
    unicodeLength,
    open: openChat,
    close: closeChat,
  });
})();
